    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        String entrada = javax.swing.JOptionPane.showInputDialog(this, "Escribe el nombre del archivo (ej: nota.txt):");

        if (entrada != null && !entrada.trim().isEmpty()) {
            
            String strBloques = javax.swing.JOptionPane.showInputDialog(this, "¿Cuántos bloques necesita este archivo?");
            
            if (strBloques != null && !strBloques.trim().isEmpty()) {
                try {
                    int bloquesNecesarios = Integer.parseInt(strBloques);
                    
                    String nombreFinal;
                    String extensionFinal;
                    if (entrada.contains(".")) {
                        int ultimoPunto = entrada.lastIndexOf(".");
                        nombreFinal = entrada.substring(0, ultimoPunto);
                        extensionFinal = entrada.substring(ultimoPunto); 
                    } else {
                        nombreFinal = entrada;
                        extensionFinal = ".txt"; 
                    }

                    String carpetaDestino = obtenerCarpetaSeleccionada();
                    boolean exito = fs.crearArchivo(nombreFinal + extensionFinal, bloquesNecesarios, carpetaDestino);
                    if (exito) {
                        int primerBloque = -1;
                        for(proyecto2_so.Controladores.Archivo a : fs.getListaArchivos()){
                            if(a.getNombre().equals(nombreFinal)){
                                primerBloque = a.getBloquesAsignados().get(0);
                            }
                        }
                        
                        proyecto2_so.Modelos.Proceso nuevoProc = new proyecto2_so.Modelos.Proceso("P_Escritura", "Guardar " + nombreFinal, primerBloque);
                        fs.agregarProceso(nuevoProc);
                        
                        actualizarVista(); 
                        agregarLog("Proceso encolado: Escribir archivo '" + nombreFinal + "'.");
                    
                    } else {
                        javax.swing.JOptionPane.showMessageDialog(this, "Error: ¡No hay espacio suficiente en el disco!");
                    }
                    
                } catch (NumberFormatException e) {
                    javax.swing.JOptionPane.showMessageDialog(this, "Error: Por favor, ingresa solo números para la cantidad de bloques.");
                }
            }
        }
    
    
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        int filaSeleccionada = tablaAsignacion.getSelectedRow();

        if (filaSeleccionada >= 0) {
            String nombreArchivo = tablaAsignacion.getValueAt(filaSeleccionada, 0).toString();
            proyecto2_so.Modelos.Proceso nuevoProc = new proyecto2_so.Modelos.Proceso("P_Borrado", "Eliminar " + nombreArchivo, 0);
            fs.agregarProceso(nuevoProc);
            boolean borrado = fs.eliminarArchivo(nombreArchivo);
            
            if (borrado) {
                actualizarVista(); 
                agregarLog("Éxito: Se eliminó el archivo '" + nombreArchivo + "' y se liberaron sus bloques.");
                javax.swing.JOptionPane.showMessageDialog(this, "¡Archivo '" + nombreArchivo + "' eliminado con éxito!");
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, selecciona un archivo en la TABLA de la derecha antes de darle a Eliminar.");
        }
    
    }//GEN-LAST:event_jButton3ActionPerformed

    private void jButton4ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton4ActionPerformed
        int filaSeleccionada = tablaAsignacion.getSelectedRow();
        
        if (filaSeleccionada >= 0) {
            String nombreActual = tablaAsignacion.getValueAt(filaSeleccionada, 0).toString();
            String extensionActual = tablaAsignacion.getValueAt(filaSeleccionada, 1).toString(); // Sacamos la extensión
            
            String nuevoNombre = javax.swing.JOptionPane.showInputDialog(this, "Escribe el nuevo nombre para '" + nombreActual + "':");
            
            if (nuevoNombre != null && !nuevoNombre.trim().isEmpty()) {
                
                if (!nuevoNombre.contains(".")) {
                    nuevoNombre = nuevoNombre + extensionActual;
                }
                
                boolean exito = fs.renombrarArchivo(nombreActual, nuevoNombre);
                
                if (exito) {
                    actualizarVista();
                    agregarLog("Modificación: Archivo '" + nombreActual + "' renombrado a '" + nuevoNombre + "'.");
                } else {
                    javax.swing.JOptionPane.showMessageDialog(this, "Error al renombrar el archivo.");
                }
            }
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Por favor, selecciona un archivo en la TABLA primero.");
        }
    
    }//GEN-LAST:event_jButton4ActionPerformed

